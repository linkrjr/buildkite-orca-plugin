// Regenerates src/emoji-data.ts from a checkout of https://github.com/buildkite/emojis.
// Usage: bun scripts/generate-emoji-data.ts <emojis checkout> [--sync-assets]
// --sync-assets also replaces assets/emoji/ with the images the table uses, each re-encoded as a PNG
// on a transparent 3:1 canvas (needs ImageMagick: `magick`, or `convert` for ImageMagick 6).
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

type Entry = { name: string; image: string; aliases: string[]; unicode?: string }

const [source, flag] = process.argv.slice(2)
if (!source) throw new Error('Usage: bun scripts/generate-emoji-data.ts <emojis checkout> [--sync-assets]')

const read = (file: string): Entry[] => JSON.parse(readFileSync(join(source, file), 'utf8'))
const pluginDir = join(import.meta.dirname, '..')

// Orca's Image only accepts these formats, so shortcodes backed by a GIF are left out and get stripped.
const ORCA_IMAGE = /\.(?:png|jpe?g|webp)$/i

const buildkite: Record<string, string> = {}
const files = new Set<string>()
for (const { name, image, aliases } of read('img-buildkite-64.json')) {
  if (!ORCA_IMAGE.test(image)) continue
  const file = image.split('/').pop() as string
  files.add(file)
  for (const key of [name, ...aliases]) buildkite[key] = file
}

const unicode: Record<string, string> = {}
for (const { name, aliases, unicode: codepoints } of read('img-apple-64.json')) {
  if (!codepoints) continue
  const char = String.fromCodePoint(...codepoints.split('-').map((hex) => parseInt(hex, 16)))
  for (const key of [name, ...aliases]) unicode[key] = char
}

const table = (name: string, entries: Record<string, string>) =>
  `export const ${name}: Record<string, string> = {\n${Object.keys(entries)
    .sort()
    .map((key) => `  ${JSON.stringify(key)}: ${JSON.stringify(entries[key])}`)
    .join(',\n')}\n}\n`

writeFileSync(
  join(pluginDir, 'src/emoji-data.ts'),
  `// Generated by scripts/generate-emoji-data.ts from https://github.com/buildkite/emojis (img-buildkite-64.json and img-apple-64.json).
// BUILDKITE_EMOJI maps a shortcode or alias to its file in assets/emoji/; UNICODE_EMOJI maps a
// standard shortcode or alias to the emoji character. Lookups must use Object.hasOwn.
${table('BUILDKITE_EMOJI', buildkite)}
${table('UNICODE_EMOJI', unicode)}`
)

if (flag === '--sync-assets') {
  // Orca's Image renders `size="xs"` 48px wide whatever the picture's shape, so every image gets the
  // same 3:1 canvas: the logo is scaled to the canvas height (kept whole, so a wide one comes out
  // smaller), centered, and Orca draws it about 16px tall.
  const magick = ['magick', 'convert'].find((tool) => {
    try {
      execFileSync(tool, ['-version'], { stdio: 'ignore' })
      return true
    } catch {
      return false
    }
  })
  if (!magick) throw new Error('--sync-assets needs ImageMagick (`brew install imagemagick`)')
  const dest = join(pluginDir, 'assets/emoji')
  rmSync(dest, { recursive: true, force: true })
  mkdirSync(dest, { recursive: true })
  for (const file of files) {
    execFileSync(magick, [
      '-quiet',
      join(source, 'img-buildkite-64', file),
      '-background', 'none',
      '-resize', '192x64',
      '-gravity', 'center',
      '-extent', '192x64',
      '-strip',
      '-define', 'png:compression-level=9',
      `PNG32:${join(dest, file)}`
    ])
  }
}
